ipcMain.handle('ntfy-send', async (_, opts) => {
  return new Promise((resolve) => {
    try {
      const server = (opts.server || 'https://ntfy.sh').replace(/\/+$/, '');
      const url = new URL(server + '/' + encodeURIComponent(opts.topic || ''));
      const body = Buffer.from(String(opts.message || ''), 'utf8');
      const mod = url.protocol === 'http:' ? require('http') : https;
      const headers = { 'Content-Type': 'text/plain; charset=utf-8', 'Content-Length': body.length };
      if (opts.title)    headers['Title']    = String(opts.title).replace(/[^\x20-\x7E]/g, '');   // ASCII-safe
      // Tags and Priority are HTTP header values too: a non-ASCII tag (an emoji,
      // an accent) throws ERR_INVALID_CHAR and loses the WHOLE notification.
      if (opts.tags) {
        const t = String(opts.tags).replace(/[^\x20-\x7E]/g, '').replace(/[^a-zA-Z0-9_,\-]/g, '').replace(/^,+|,+$/g,'');
        if (t) headers['Tags'] = t;
      }
      // ntfy takes a priority as 1..5 OR as one of its five words. The
      // interface sends the words ("high", "urgent"), and parseInt('high') is
      // NaN: parsed as a number only, the header would be dropped and EVERY
      // alert (failure, cancel, suspect card) delivered at the same level as
      // "transfer complete". Silent, and exactly the notifications meant to
      // wake a phone. Hence the word table below.
      if (opts.priority) {
        const NAMED = { min:1, low:2, default:3, high:4, urgent:5, max:5 };
        const raw = String(opts.priority).trim().toLowerCase();
        const p = Object.prototype.hasOwnProperty.call(NAMED, raw) ? NAMED[raw] : parseInt(raw, 10);
        if (Number.isFinite(p) && p >= 1 && p <= 5) headers['Priority'] = String(p);
      }
      const req = mod.request(url, { method: 'POST', headers, timeout: 8000 }, res => {
        res.resume();
        resolve({ ok: res.statusCode >= 200 && res.statusCode < 300, status: res.statusCode });
      });
      req.on('error', e => resolve({ ok: false, error: e.message }));
      req.on('timeout', () => { req.destroy(); resolve({ ok: false, error: 'timeout' }); });
      req.write(body); req.end();
    } catch (e) { resolve({ ok: false, error: e.message }); }
  });
});
ipcMain.handle('is-removable', async (_, p) => {
  try {
    // Asynchronous: asked while an ingest may be running, it must not
    // stop the copy while the system answers.
    if (process.platform === 'darwin') {
      const out = await tryExecFile('diskutil', ['info', String(p)], 5000);
      return /Removable Media:\s*Removable/i.test(out);
    }
    if (process.platform === 'win32') {
      const m = String(p).match(/^([A-Za-z]):/);
      if (!m) return false;
      const out = await tryExecFile('powershell', ['-NoProfile', '-Command',
        `(Get-CimInstance Win32_LogicalDisk -Filter "DeviceID='${m[1]}:'").DriveType`], 5000);
      return String(out).trim() === '2';  // 2 = Removable Disk
    }
    if (process.platform === 'linux') {
      // A mount under the desktop automount roots is removable media by
      // definition; the sysfs 'removable' flag confirms it when readable
      // (SD readers over USB report 1; some internal readers report 0,
      // which is why the mountpoint heuristic comes first).
      if (/^\/(media|run\/media)\//.test(String(p))) return true;
      try {
        const dev = execFileSync('findmnt', ['-n', '-o', 'SOURCE', p],
          { encoding: 'utf8', timeout: 5000, stdio: ['ignore', 'pipe', 'ignore'] }).trim();
        const base = path.basename(dev);
        for (const rel of [base + '/removable', base + '/../removable']) {
          try {
            return fs.readFileSync(path.join('/sys/class/block', rel), 'utf8').trim() === '1';
          } catch (_) {}
        }
      } catch (_) {}
      return false;
    }
    return false;
  } catch (_) { return false; }
});
ipcMain.handle('report-write-named', async (_, destPath, name, content, appendIfExists) => {
  // SECURITY: `name` must be a plain file name inside destPath. A crafted name
  // like "../../../../etc/cron.d/x" would let the renderer write anywhere the
  // user can (silent persistence). Reject any name with a path separator or
  // "..", and confirm the resolved path really sits inside destPath.
  try {
    const base = String(name || '');
    if (!base || base === '.' || base === '..' || /[\/\\]/.test(base)) return false;
    // Windows leftovers: ':' would write an NTFS alternate data stream (invisible
    // content); the reserved device names silently go nowhere. Other chars are
    // illegal in filenames anyway.
    if (/[:<>"|?*\x00-\x1f]/.test(base)) return false;
    if (/^(con|prn|aux|nul|com[1-9]|lpt[1-9])(\.|$)/i.test(base)) return false;
    const target = path.resolve(destPath, base);
    if (!pathContains(destPath, target)) return false;
    // A CSV cannot be read back (only the HTML/JSON carry the history), so when
    // it is the ONLY report on the drive the caller asks for an APPEND: the
    // rows of this run go under the existing ones, header skipped. Rewriting
    // it from today's cards would erase the whole ingest history of the drive.
    if (appendIfExists) {
      const text = String(content);
      const nl = text.indexOf('\n');
      const header = (nl >= 0 ? text.slice(0, nl) : text).replace(/\r$/, '');
      const body = nl >= 0 ? text.slice(nl + 1) : '';
      const ext = path.extname(base), stem = ext ? base.slice(0, -ext.length) : base;
      // The first sibling whose header matches gets the rows; a file from an
      // earlier version with other columns is left alone — appending to it
      // would shift every new row by a column — and a "-2" file is started.
      for (let i = 1; i < 100; i++) {
        const cand = i === 1 ? target : path.join(destPath, `${stem}-${i}${ext}`);
        let cst = null; try { cst = fs.statSync(cand); } catch (_) {}
        if (!cst) { writeFileAtomic(cand, text); return true; }
        // Appending means reading the whole file back first. A report that has
        // grown past anything a report can be is left alone, and the rows go
        // to a sibling instead of being lost.
        if (!cst.isFile() || cst.size > REPORT_MAX_BYTES) continue;
        const old = fs.readFileSync(cand, 'utf8');
        if (old.split('\n')[0].replace(/\r$/, '') !== header) continue;
        if (body) writeFileAtomic(cand, old + (old.endsWith('\n') || !old.length ? '' : '\n') + body);
        return true;
      }
      return false;
    }
    writeFileAtomic(target, content);
    return true;
  } catch (_) { return false; }
});
// ─── Commands typed in Settings: asked once, by the main process ───────────
// The post-ingest command and the card handoff run a program on this computer.
// The interface hands them over, so a script injected into the interface
// (through a card label, a report read from a shared drive...) could run
// anything if the main process obeyed blindly. So the FIRST time a given
// command is about to run, the main process shows a system dialog with the
// exact command, and runs it only if the operator says so. The answer is
// remembered for that exact command, in a file the interface cannot write.
// Nothing can answer the dialog but a person.
const TRUSTED_PATH = path.join(app.getPath('userData'), 'ingesto-trusted-commands.json');
function loadTrustedCommands() {
  try { const a = JSON.parse(fs.readFileSync(TRUSTED_PATH, 'utf8')); return Array.isArray(a) ? a.filter(x => typeof x === 'string') : []; }
  catch (_) { return []; }
}
async function approveCommand(kind, tpl) {
  const key = kind + '\u0000' + JSON.stringify(tpl);
  const list = loadTrustedCommands();
  if (list.includes(key)) return true;
  const shown = tpl.map(t => (t === '' || /[\s"']/.test(t)) ? JSON.stringify(t) : t).join(' ');
  const opts = {
    type: 'warning',
    buttons: [i18n.t('Run'), i18n.t('Do not run')],
    defaultId: 1, cancelId: 1,
    title: i18n.t('Run this command?'),
    message: kind === 'hook'
      ? i18n.t('ingesto is about to run the post-ingest command for the first time.')
      : i18n.t('ingesto is about to run the card handoff command for the first time.'),
    detail: shown + '\n\n' + i18n.t('It comes from Settings. Run it only if you typed it yourself. ingesto will not ask again for this exact command.'),
  };
  let r = null;
  try { r = await (mainWindow ? dialog.showMessageBox(mainWindow, opts) : dialog.showMessageBox(opts)); }
  catch (_) { r = null; }
  if (!r || r.response !== 0) return false;
  list.push(key);
  while (list.length > 20) list.shift();
  try { fs.writeFileSync(TRUSTED_PATH, JSON.stringify(list, null, 1)); } catch (_) {}
  return true;
}
// The hook's arguments carry values ({card}, {destPath}...) that change at
// every run, so what is approved is the command AS TYPED (tpl), and each
// argument must be that template with only its variables filled in.
const HOOK_VARS = /(\{(?:destPath|card|count|bytes|result)\})/;
function argvMatchesTemplate(argv, tpl) {
  if (!Array.isArray(tpl) || tpl.length !== argv.length || !tpl.every(t => typeof t === 'string')) return false;
  if (argv[0] !== tpl[0]) return false;            // the program is never a variable
  const esc = x => x.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  for (let i = 1; i < tpl.length; i++) {
    const re = '^' + tpl[i].split(HOOK_VARS).map((p, j) => j % 2 ? '[\\s\\S]*' : esc(p)).join('') + '$';
    if (!new RegExp(re).test(String(argv[i]))) return false;
  }
  return true;
}
ipcMain.handle('run-hook', async (_, argv, tpl) => {
  // SECURITY: the post-ingest hook runs WITHOUT a shell. The renderer sends
  // an argument array [program, ...args]; each argument is passed verbatim to
  // the OS, never concatenated into a command line. A hostile card name, or a
  // path with spaces, therefore cannot inject anything or split into extra
  // arguments. (Running the whole string through a shell, as exec(command)
  // does, would be a command-injection surface.)
  try {
    if (!Array.isArray(argv) || !argv.length || typeof argv[0] !== 'string' || !argv[0].trim()) {
      return { ok: false, error: 'empty or malformed hook command' };
    }
    if (!argvMatchesTemplate(argv, tpl)) return { ok: false, error: 'the command does not match the one in Settings' };
    if (!(await approveCommand('hook', tpl))) return { ok: false, error: 'not run: the command was not approved' };
    const program = argv[0];
    const args = argv.slice(1).map(a => String(a == null ? '' : a));
    // spawn (not execFile): no output pipes, so no maxBuffer cap that would kill
    // a long, chatty rsync, and NO timeout — a legitimate multi-hundred-GB hook
    // must be free to run for as long as it needs. It is fire-and-forget and
    // unref'd, so a stuck hook never blocks the app. stdio:'ignore' avoids the
    // EPIPE-on-quit failure that piped output would cause.
    // Note: on Windows this cannot launch a .bat/.cmd directly (no shell) — wrap
    // such hooks in an .exe or call the interpreter explicitly.
    const { spawn } = require('child_process');
    const child = spawn(program, args, { windowsHide: true, stdio: 'ignore' });
    return await new Promise(resolve => {
      let settled = false;
      child.on('error', e => { if (!settled) { settled = true; resolve({ ok: false, error: e.message }); } });
      child.on('spawn', () => { if (!settled) { settled = true; resolve({ ok: true }); } });
      setTimeout(() => { if (!settled) { settled = true; resolve({ ok: true }); } }, 800);
      if (child.unref) child.unref();
    });
  } catch (e) { return { ok: false, error: e.message }; }
});
// ─── The handoff ────────────────────────────────────────────────────────────
// Writes one card's document to a scratch file, runs the operator's command
// with that path as its LAST argument, and removes the file when the command
// returns. The path is appended, never substituted into the command: there is
// no token for anything here, so nothing the card carries can end up inside
// the command line.
//
// `keep` is the dry run: the file survives and is revealed, so a script can be
// built against a real document without a card anywhere near it.
ipcMain.handle('handoff', async (_, payload, argv, keep) => {
  let file = null;
  try {
    if (!Array.isArray(argv) || !argv.length || typeof argv[0] !== 'string' || !argv[0].trim())
      return { ok: false, error: 'empty or malformed handoff command' };
    if (!argv.every(a => typeof a === 'string'))
      return { ok: false, error: 'empty or malformed handoff command' };
    if (!payload || typeof payload !== 'object')
      return { ok: false, error: 'no document to hand over' };
    // Asked once per command, by the system, not by the interface.
    if (!(await approveCommand('handoff', argv)))
      return { ok: false, error: 'not run: the command was not approved' };

    // Filled in HERE, not in the interface: only this side can ask the OS.
    const srcPath = String((payload.source && payload.source.path) || '');
    const ident = volumeIdentity(srcPath);
    payload.source = Object.assign({}, payload.source, {
      volumeUUID: ident.uuid,
      removable: ident.removable,
      stillMounted: ident.mounted,
    });
    // A card that is no longer there cannot be handed to anything.
    if (!ident.mounted) payload.safeToErase = false;
    // And a dry run is never an authorisation, whatever reached this side.
    // The interface already answers no; this is the second lock, on the side
    // that actually hands the document to the command.
    if (payload.dryRun === true) payload.safeToErase = false;

    const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'ingesto-handoff-'));
    file = path.join(dir, 'handoff.json');
    fs.writeFileSync(file, JSON.stringify(payload, null, 2), { encoding: 'utf8', mode: 0o600 });

    const { spawn } = require('child_process');
    const child = spawn(argv[0], argv.slice(1).map(a => String(a == null ? '' : a)).concat([file]),
                        { windowsHide: true, stdio: 'ignore' });
    const res = await new Promise(resolve => {
      let settled = false;
      const done = (v) => { if (!settled) { settled = true; resolve(v); } };
      child.on('error', e => done({ ok: false, error: e.message }));
      child.on('exit', code => done({ ok: code === 0, code }));
      // Generous, because a handoff can legitimately be waiting for a human to
      // answer another application's dialog. On timeout the child is left
      // alone and the file is left with it: killing a program that may be
      // mid-dialog, or pulling the document out from under it, is worse than
      // one stale file in a directory the OS empties by itself.
      const t = setTimeout(() => { file = null; done({ ok: false, error: 'still running after 30 minutes' }); },
                           30 * 60 * 1000);
      // The TIMER is unref'd so a handoff still waiting cannot hold the
      // application open at quit. The CHILD is not: this handler resolves on
      // its exit, and detaching it leaves nothing for the event loop to wait
      // on, so the promise never settles. (The post-ingest hook next door can
      // unref its child because it resolves the moment the child spawns.)
      if (t.unref) t.unref();
    });
    if (keep) {
      file = null;                                  // the dry run keeps its document
      try { shell.showItemInFolder(path.join(dir, 'handoff.json')); } catch (_) {}
      return Object.assign({}, res, { file: path.join(dir, 'handoff.json') });
    }
    return res;
  } catch (e) {
    return { ok: false, error: e.message };
  } finally {
    // rmSync, not rmdir: a command that wrote its own files beside the document
    // would otherwise leave the whole directory behind.
    if (file) { try {
      const dir = path.dirname(file);
      // Only ever the folder this call created: inside the system temp folder,
      // named as mkdtemp named it. Anything else is left where it is.
      if (pathContains(os.tmpdir(), dir) && path.basename(dir).startsWith('ingesto-handoff-')) safeRmTree(dir);
    } catch (_) {} }
  }
});
ipcMain.handle('report-read', async (_, destPath) => {
  // Prefer the HTML's embedded data; fall back to the JSON sidecar when HTML isn't written.
  // `tooBig` separates "this file is not one we are willing to read" from "we
  // read it and it made no sense". Same outcome for the caller (keep the old
  // file, do not start the history over), but the two are not the same event
  // and only one of them means the report is corrupt.
  let htmlExists = false, blockFound = false, tooBig = false;
  try {
    const fp = path.join(destPath, 'INGESTO_report.html');
    // Sizes checked BEFORE reading, not after. This file sits on a drive
    // anyone can write to, and an ingest station left running unattended
    // should not be stoppable by dropping a large file into a folder.
    const rst = fs.statSync(fp);
    if (!rst.isFile()) throw new Error('not a file');
    htmlExists = true;
    if (rst.size > REPORT_MAX_BYTES) { tooBig = true; throw new Error('report too large'); }
    const html = fs.readFileSync(fp, 'utf8');
    // Reports carry a gzip+base64 data block; those written by earlier versions
    // carry plain JSON. Both must be readable, or updating an existing report
    // would silently start it over from scratch and lose its history.
    const mz = html.match(/<script id="ingesto-report-data" type="application\/gzip\+base64">([\s\S]*?)<\/script>/);
    if (mz) {
      blockFound = true;
      const b64 = mz[1].trim();
      // The block itself is already bounded: it came out of a file that was
      // measured before it was read. What is NOT bounded is what it expands
      // to. A compressed block says nothing about its own output, and 400 KB
      // of gzip is 400 MB of zeros. maxOutputLength makes zlib refuse instead
      // of allocating it.
      const raw = zlib.gunzipSync(Buffer.from(b64, 'base64'), { maxOutputLength: REPORT_JSON_MAX_BYTES });
      return JSON.parse(raw.toString('utf8'));
    }
    const m = html.match(/<script id="ingesto-report-data" type="application\/json">([\s\S]*?)<\/script>/);
    if (m) { blockFound = true; return JSON.parse(m[1]); }
  } catch (e) {
    // zlib refuses past maxOutputLength rather than allocating the buffer.
    if (e && e.code === 'ERR_BUFFER_TOO_LARGE') tooBig = true;
  }
  try {
    const jp = path.join(destPath, 'INGESTO_report.json');
    const jst = fs.statSync(jp);
    if (!jst.isFile() || jst.size > REPORT_JSON_MAX_BYTES) throw new Error('report sidecar too large');
    const j = JSON.parse(fs.readFileSync(jp, 'utf8'));
    if (j && Array.isArray(j.records)) return { created: j.created, records: j.records };
  } catch (_) {}
  // A report file that EXISTS but cannot be read is not the same as no report.
  // Returning null there would make the next ingest rewrite the destination's
  // report with only today's cards: the client-facing history gone, silently.
  // Say so instead, so the caller can preserve the old file and warn.
  if (htmlExists) return { unreadable: true, blockFound, tooBig, records: [] };
  return null;
});
